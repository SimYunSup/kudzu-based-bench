#!/usr/bin/env node
// Materialize the commerce catalog as a relative TypeScript module.
//
// Kudzu (0.8.x through 0.9.0, re-verified on 0.9.0) rejects every package
// (non-relative) import referenced outside
// a JSX event handler, so a compiled page cannot `import { buildCatalog }
// from "@otw/commerce-data"`. The generator runs here instead and the pages
// import ../generated/catalog — a relative module, which Kudzu does compile
// and whose JSON-safe immutable arrays it folds into static output.
//
// Catalog size comes from OTW_CATALOG_SIZE (100 | 1000 | 10000, default 100)
// so the build-scaling track can sweep it without touching source.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildCatalog, catalogSizeFromEnv } from "@otw/commerce-data";

const appDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const size = catalogSizeFromEnv(process.env.OTW_CATALOG_SIZE);
const catalog = buildCatalog(size);

const outDir = join(appDir, "src", "generated");
mkdirSync(outDir, { recursive: true });

// Types are duplicated rather than re-exported: importing them from the
// package would put a package specifier back into compiled source. They are
// erased at compile time, but Kudzu's guard runs on the AST, not on emit.
writeFileSync(
  join(outDir, "catalog.ts"),
  `// GENERATED by scripts/gen-catalog.mjs — do not edit, do not commit.
export interface Money { amount: number; currencyCode: string }
export interface ProductImage { url: string; altText: string; width: number; height: number }
export interface SelectedOption { name: string; value: string }
export interface ProductVariant {
  id: string;
  title: string;
  availableForSale: boolean;
  selectedOptions: SelectedOption[];
  price: Money;
}
export interface ProductOption { name: string; values: string[] }
export interface Product {
  id: string;
  handle: string;
  title: string;
  description: string;
  descriptionHtml: string;
  featuredImage: ProductImage;
  images: ProductImage[];
  options: ProductOption[];
  variants: ProductVariant[];
  priceRange: { minVariantPrice: Money; maxVariantPrice: Money };
  tags: string[];
  collection: string;
  availableForSale: boolean;
  updatedAt: string;
}
export interface Collection {
  handle: string;
  title: string;
  description: string;
  productHandles: string[];
}
export interface MenuItem { title: string; path: string }
export interface StaticPage { handle: string; title: string; bodyHtml: string }

export const products: Product[] = ${JSON.stringify(catalog.products)};
export const collections: Collection[] = ${JSON.stringify(catalog.collections)};
export const menu: MenuItem[] = ${JSON.stringify(catalog.menu)};
export const pages: StaticPage[] = ${JSON.stringify(catalog.pages)};
`
);

// Listing rows are emitted as a literal array, not derived in page source.
// Kudzu only recognizes a keyed-list selector pipeline (`filter`/`toSorted`)
// when its source is a local array state anchor or a named relative import of
// an exported JSON-safe const array. Building the rows in the page with a
// loop produces an ordinary local, and `useState(rows)` hands the component a
// signal object, so `rows.filter(...)` fails at render with
// "items.filter is not a function". Emitting the literal here is the shape
// the compiler accepts.
const BASE = "/kudzu-based-bench/shop-kudzu";
const won = new Intl.NumberFormat("ko-KR");
const tile = product => ({
  handle: product.handle,
  title: product.title,
  href: `${BASE}/product/${product.handle}`,
  imageUrl: `${BASE}${product.featuredImage.url}`,
  imageAlt: product.featuredImage.altText,
  priceLabel: `${won.format(product.priceRange.minVariantPrice.amount)}원`,
  price: product.priceRange.minVariantPrice.amount,
  updated: Date.parse(product.updatedAt),
  collection: product.collection
});

/** Listing page size, matching a normal storefront grid. */
const LISTING_LIMIT = 48;

writeFileSync(
  join(outDir, "tiles.ts"),
  `// GENERATED by scripts/gen-catalog.mjs — do not edit, do not commit.
export interface Tile {
  handle: string;
  title: string;
  href: string;
  imageUrl: string;
  imageAlt: string;
  priceLabel: string;
  price: number;
  updated: number;
  collection: string;
}

export const searchTiles: Tile[] = ${JSON.stringify(catalog.products.slice(0, LISTING_LIMIT).map(tile))};
${catalog.collections
  .map(collection => {
    const rows = catalog.products
      .filter(product => product.collection === collection.handle)
      .slice(0, LISTING_LIMIT)
      .map(tile);
    return `export const tiles_${collection.handle}: Tile[] = ${JSON.stringify(rows)};`;
  })
  .join("\n")}
`
);

console.log(`gen-catalog: ${catalog.products.length} products, ${catalog.collections.length} collections`);
